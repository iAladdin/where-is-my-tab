import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  Bookmark,
  Combine,
  Copy,
  ExternalLink,
  Layers3,
  Search,
  Trash2,
  TrendingUp,
  X
} from 'lucide';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(rootDir, 'src', 'lib', 'icons.js');

const icons = {
  search: Search,
  close: X,
  bookmark: Bookmark,
  open: ExternalLink,
  merge: Combine,
  stack: Layers3,
  trend: TrendingUp,
  copy: Copy,
  trash: Trash2
};

const source = `// Generated by scripts/generate-ui-icons.mjs from Lucide.
// Do not edit icon geometry by hand. See THIRD_PARTY_NOTICES.md for licensing.

const SVG_NAMESPACE = 'http://www.w3.org/2000/svg';

const ICONS = Object.freeze(${JSON.stringify(icons, null, 2)});

export function createIcon(name) {
  const resolvedName = Object.hasOwn(ICONS, name) ? name : 'close';
  const svg = document.createElementNS(SVG_NAMESPACE, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.classList.add('action-icon', 'lucide', \`lucide-\${resolvedName}\`);

  for (const [tagName, attributes] of ICONS[resolvedName]) {
    const node = document.createElementNS(SVG_NAMESPACE, tagName);
    for (const [attribute, value] of Object.entries(attributes)) {
      node.setAttribute(attribute, String(value));
    }
    svg.append(node);
  }

  return svg;
}
`;

await writeFile(outputPath, source, 'utf8');
console.log(outputPath);
